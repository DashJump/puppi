import { createRequire } from "node:module";
import { join } from "node:path";

import type { RegisteredAdapter } from "@puppi/sdk";

import type { ManifestAsset } from "./manifest.js";

/**
 * `puppi-env.d.ts`: asset key to row type, and connection name to client type.
 *
 * Keys stay string literals so the compile pass can read them. The build
 * does not need this file to exist. An asset with no schema is `Row`.
 * A connection is the adapter's `Client` when that package resolves, otherwise `unknown`.
 */
export const TYPES_FILE = "puppi-env.d.ts";

/** Connection name -> the TypeScript type `ctx.connection(name)` returns. */
export type ConnectionTypes = Record<string, string>;

export function declarationFile(
  assets: ManifestAsset[],
  connections: ConnectionTypes = {},
): string {
  const entries = [...assets]
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((asset) => `    ${JSON.stringify(asset.key)}: ${rowType(asset)};`);

  const clients = Object.keys(connections)
    .sort()
    .map((name) => `    ${JSON.stringify(name)}: ${connections[name]};`);

  return [
    "// Generated by `puppi build` from the project's asset declarations.",
    "// Do not edit: it is rewritten on every build. Keep it out of version control.",
    "//",
    "// Augments `PuppiAssets` in `@puppi/sdk`, which types `ctx.input()`: every",
    "// declared key autocompletes, a typo is a type error, and the returned",
    "// `TableRef` carries the upstream's row type. A file asset is `FileAsset`,",
    "// and `ctx.input()` returns a file ref. `PuppiConnections` does the",
    "// same for `ctx.connection()`, from the connections in puppi.config.ts.",
    "",
    'declare module "@puppi/sdk" {',
    "  interface PuppiAssets {",
    ...entries,
    "  }",
    "",
    "  interface PuppiConnections {",
    ...clients,
    "  }",
    "}",
    "",
    "export {};",
    "",
  ].join("\n");
}

/**
 * The client type of each declared connection. An adapter the bundle carries
 * is typed from the `clientModule` its declaration names. `defineConfig`
 * sets that to `@puppi/adapter-<type>` for a connector module; the import is
 * emitted only when the package resolves, so a missing install is `unknown`
 * rather than a broken import. A relative `clientModule` is the project's
 * own file and is emitted as written. A connection the bundle did not
 * register is `unknown`: the client is the one the bundle carries.
 */
export function connectionTypes(
  dir: string,
  connections: Record<string, { type: string }>,
  adapters: Record<string, RegisteredAdapter> = {},
): ConnectionTypes {
  const resolve = createRequire(join(dir, "package.json"));

  return Object.fromEntries(
    Object.entries(connections).map(([name, { type }]) => {
      const bundled = adapters[type];

      return [name, bundled ? clientType(resolve, bundled.client_module) : "unknown"];
    }),
  );
}

/**
 * A path (`./src/clearbit.js`) is the project's file. Anything else is a
 * package specifier, emitted only when this project can resolve it.
 */
function clientType(resolve: ReturnType<typeof createRequire>, spec: string | undefined): string {
  if (!spec) return "unknown";

  if (!spec.startsWith(".") && !spec.startsWith("/") && !canResolve(resolve, spec)) {
    return "unknown";
  }

  return `import(${JSON.stringify(spec)}).Client`;
}

function canResolve(resolve: ReturnType<typeof createRequire>, spec: string): boolean {
  try {
    resolve.resolve(spec);

    return true;
  } catch {
    return false;
  }
}

function rowType(asset: ManifestAsset): string {
  if (asset.config["output"] === "file") return `import("@puppi/sdk").FileAsset`;

  const columns = asset.schema?.columns;

  if (!columns) return "Record<string, unknown>";

  const fields = columns.map(({ name, type }) => `${property(name)}: ${tsType(type)}`);

  return `{ ${fields.join("; ")} }`;
}

/**
 * The adapter's type vocabulary -> TypeScript. `string|null` is a union, an
 * integer or float is a `number`, and anything structured is `unknown` —
 * the contract records that a column is `json`, not what is inside it.
 */
function tsType(columnType: string): string {
  const parts = [
    ...new Set(
      columnType
        .split("|")
        .map((part) => part.trim().toLowerCase())
        .filter(Boolean)
        .map((part) => SCALAR[part] ?? "unknown"),
    ),
  ];

  if (parts.length === 0 || parts.includes("unknown")) return "unknown";

  return parts.join(" | ");
}

const SCALAR: Record<string, string> = {
  string: "string",
  integer: "number",
  float: "number",
  number: "number",
  boolean: "boolean",
  null: "null",
};

function property(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}
